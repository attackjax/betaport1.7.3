    public record Rule(int block, String item, int damage, int count, int extra, int oneIn) {
        public boolean none() {
            return item.equals("-");
        }

        public boolean self() {
            return item.equals("self");
        }

        public boolean crops() {
            return item.equals("crops");
        }

        public int roll(IntUnaryOperator nextInt) {
            int n = count + (extra > 0 ? nextInt.applyAsInt(extra) : 0);
            return oneIn > 1 && nextInt.applyAsInt(oneIn) != 0 ? 0 : n;
        }
    }

    public static Rule rule(int block) {
        for (String line : RULES) {
            String[] parts = line.split(" ");
            if (Integer.parseInt(parts[0]) != block) {
                continue;
            }
            String item = parts[1];
            int damage = -1;
            if (item.contains(":")) {
                String d = item.substring(item.indexOf(':') + 1);
                damage = d.equals("meta") ? -1 : Integer.parseInt(d);
                item = item.substring(0, item.indexOf(':'));
            }
            int count = 0;
            int extra = 0;
            int oneIn = 1;
            if (parts.length > 2) {
                String[] c = parts[2].split("\\+");
                count = Integer.parseInt(c[0]);
                extra = c.length > 1 ? Integer.parseInt(c[1]) : 0;
            }
            if (parts.length > 3) {
                oneIn = Integer.parseInt(parts[3].substring(2));
            }
            return new Rule(block, item, damage, count, extra, oneIn);
        }
        return null;
    }

    public static int[] crops(int age, IntUnaryOperator nextInt) {
        int seeds = 0;
        for (int i = 0; i < 3; i++) {
            if (nextInt.applyAsInt(15) <= age) {
                seeds++;
            }
        }
        return new int[] {age == 7 ? 1 : 0, seeds};
    }

    public static String harvest(int block) {
        for (String line : LINES) {
            if (line.startsWith("harvest " + block + " ") || line.equals("harvest " + block)) {
                return line.substring(("harvest " + block).length()).trim();
            }
        }
        return null;
    }

    public static List<String> drops(int block) {
        List<String> found = new ArrayList<>();
        for (String line : LINES) {
            if (line.startsWith("drop " + block + ":")) {
                found.add(line);
            }
        }
        return found;
    }
